func TestBlueGreen250UpgradeOldWritesGuardReleaseAndReplay(t *testing.T) {
	db, conn := migration250Fixture(t)
	var before, after int64
	require.NoError(t, db.QueryRow("SELECT relfilenode FROM pg_class WHERE oid='usage_logs'::regclass").Scan(&before))
	require.NoError(t, runMigration250(t, db))
	require.NoError(t, db.QueryRow("SELECT relfilenode FROM pg_class WHERE oid='usage_logs'::regclass").Scan(&after))
	require.Equal(t, before, after)
	_, err := db.Exec(`INSERT INTO usage_logs(api_key_id,actual_cost) VALUES(2,3.5);
        UPDATE channel_model_pricing SET input_price=3 WHERE id=1;
        INSERT INTO channel_pricing_intervals(id,input_price) VALUES(1,4);
        UPDATE usage_logs SET cache_creation_30m_tokens=30,cache_creation_12h_tokens=12 WHERE id=1`)
	require.NoError(t, err)
	for _, table := range blueGreen250PricingTables {
		_, err = db.Exec(fmt.Sprintf("INSERT INTO %s(id,cache_write_12h_price) VALUES(100,1)", table))
		require.Error(t, err)
	}
	require.NoError(t, runMigration250(t, db))
	var valid bool
	require.NoError(t, db.QueryRow(`SELECT (SELECT cache_creation_30m_tokens=0 AND cache_creation_12h_tokens=0 FROM usage_logs WHERE api_key_id=2)
        AND (SELECT cache_creation_30m_tokens=30 AND cache_creation_12h_tokens=12 FROM usage_logs WHERE id=1)
        AND (SELECT sum(actual_cost)=6 FROM usage_logs) AND (SELECT count(*)=2 FROM schema_migrations)`).Scan(&valid))
	require.True(t, valid)
	_, err = db.Exec(cache250GuardSQL(t, "release"))
	require.NoError(t, err)
	_, err = db.Exec(cache250GuardSQL(t, "release"))
	require.NoError(t, err)
	_, err = db.Exec("UPDATE channel_model_pricing SET cache_write_12h_price=0.123 WHERE id=1")
	require.NoError(t, err)
	require.NoError(t, runMigration250(t, db))
	var timeout string
	require.NoError(t, conn.QueryRowContext(context.Background(), "SHOW statement_timeout").Scan(&timeout))
	require.Equal(t, "0", timeout)
}

func TestBlueGreen250CompleteOldSchema(t *testing.T) {
	db, _ := migration250Fixture(t)
	_, err := db.Exec("DROP SCHEMA public CASCADE; CREATE SCHEMA public")
	require.NoError(t, err)
	old := fstest.MapFS{}
	names, err := fs.Glob(migrations.FS, "*.sql")
	require.NoError(t, err)
	for _, name := range names {
		if name == blueGreen250Migrations[0].Filename || name == blueGreen250Migrations[1].Filename {
			continue
		}
		raw, err := migrations.FS.ReadFile(name)
		require.NoError(t, err)
		old[name] = &fstest.MapFile{Data: raw}
	}
	require.NoError(t, applyMigrationsFS(context.Background(), db, old))
	require.NoError(t, applyMigrationsFSWithPolicy(context.Background(), db, migrations.FS,
		&blueGreenMigrationPolicy{Version: 1, Migrations: blueGreen250Migrations}))
	require.NoError(t, runMigration250(t, db))
}

func TestBlueGreen250LargeUsageTableAndSessionSettings(t *testing.T) {
	db, conn := migration250Fixture(t)
	_, err := db.Exec(`INSERT INTO usage_logs(api_key_id,payload) SELECT g,md5(g::text) FROM generate_series(1,250000) g`)
	require.NoError(t, err)
	var size, before, after int64
	require.NoError(t, db.QueryRow("SELECT pg_total_relation_size('usage_logs'),relfilenode FROM pg_class WHERE oid='usage_logs'::regclass").Scan(&size, &before))
	require.Greater(t, size, int64(blueGreenSpecialTableLimit))
	_, err = conn.ExecContext(context.Background(), "SET statement_timeout='7s'; SET lock_timeout='3s'")
	require.NoError(t, err)
	require.NoError(t, runSpecialMigration(t, conn, blueGreen250Migrations[0]))
	var statement, lock string
	require.NoError(t, conn.QueryRowContext(context.Background(), "SELECT current_setting('statement_timeout'),current_setting('lock_timeout')").Scan(&statement, &lock))
	require.Equal(t, "7s", statement)
	require.Equal(t, "3s", lock)
	require.NoError(t, runSpecialMigration(t, conn, blueGreen250Migrations[1]))
	require.NoError(t, db.QueryRow("SELECT relfilenode FROM pg_class WHERE oid='usage_logs'::regclass").Scan(&after))
	require.Equal(t, before, after)
	var valid bool
	require.NoError(t, db.QueryRow("SELECT count(*)=250001 AND bool_and(cache_creation_30m_tokens=0 AND cache_creation_12h_tokens=0) FROM usage_logs").Scan(&valid))
	require.True(t, valid)
}

func TestBlueGreen250PartialIndexRecovery(t *testing.T) {
	t.Run("索引成功账本失败", func(t *testing.T) {
		db, _ := migration250Fixture(t)
		_, err := db.Exec("ALTER TABLE schema_migrations ADD CONSTRAINT reject_249 CHECK(filename<>'249_add_usage_logs_api_key_cost_index_notx.sql')")
		require.NoError(t, err)
		require.Error(t, runMigration250(t, db))
		var before, after int64
		require.NoError(t, db.QueryRow("SELECT 'idx_usage_logs_api_key_created_cost'::regclass::oid").Scan(&before))
		_, err = db.Exec("ALTER TABLE schema_migrations DROP CONSTRAINT reject_249")
		require.NoError(t, err)
		require.NoError(t, runMigration250(t, db))
		require.NoError(t, db.QueryRow("SELECT 'idx_usage_logs_api_key_created_cost'::regclass::oid").Scan(&after))
		require.Equal(t, before, after)
	})
	t.Run("失败并发构建的无效索引", func(t *testing.T) {
		db, conn := migration250Fixture(t)
		writer, err := db.Begin()
		require.NoError(t, err)
		defer func() { _ = writer.Rollback() }()
		_, err = writer.Exec("INSERT INTO usage_logs(api_key_id) VALUES(3)")
		require.NoError(t, err)
		_, err = conn.ExecContext(context.Background(), "SET statement_timeout='200ms'")
		require.NoError(t, err)
		raw := migration250Files(t)[blueGreen250Migrations[0].Filename].Data
		_, err = conn.ExecContext(context.Background(), string(raw))
		require.Error(t, err)
		_, err = conn.ExecContext(context.Background(), "RESET statement_timeout")
		require.NoError(t, err)
		exists, valid, err := blueGreen250IndexState(context.Background(), conn)
		require.NoError(t, err)
		require.True(t, exists)
		require.False(t, valid)
		require.NoError(t, writer.Rollback())
		require.NoError(t, runMigration250(t, db))
	})
}

func TestBlueGreen250LocksAndAtomicColumnFailure(t *testing.T) {
	for _, table := range append([]string{"usage_logs", "schema_migrations"}, blueGreen250PricingTables...) {
		t.Run(table, func(t *testing.T) {
			db, conn := migration250Fixture(t)
			require.NoError(t, runSpecialMigration(t, conn, blueGreen250Migrations[0]))
			lock, err := db.Begin()
			require.NoError(t, err)
			defer func() { _ = lock.Rollback() }()
			_, err = lock.Exec("LOCK TABLE " + table + " IN ACCESS SHARE MODE")
			require.NoError(t, err)
			started := time.Now()
			require.ErrorContains(t, runSpecialMigration(t, conn, blueGreen250Migrations[1]), "立即获锁")
			require.Less(t, time.Since(started), time.Second)
		})
	}
	t.Run("250账本失败整体回滚", func(t *testing.T) {
		db, _ := migration250Fixture(t)
		_, err := db.Exec("ALTER TABLE schema_migrations ADD CONSTRAINT reject_250 CHECK(filename<>'250_openai_cache_write_ttl.sql')")
		require.NoError(t, err)
		require.Error(t, runMigration250(t, db))
		var clean bool
		require.NoError(t, db.QueryRow(`SELECT NOT EXISTS(SELECT 1 FROM pg_attribute WHERE attrelid='usage_logs'::regclass AND attname='cache_creation_12h_tokens')
            AND NOT EXISTS(SELECT 1 FROM pg_constraint WHERE conname='sub2api_bg250_price') AND (SELECT count(*)=1 FROM schema_migrations)`).Scan(&clean))
		require.True(t, clean)
		_, err = db.Exec("ALTER TABLE schema_migrations DROP CONSTRAINT reject_250")
		require.NoError(t, err)
		require.NoError(t, runMigration250(t, db))
	})
}

func TestBlueGreen250RejectsDrift(t *testing.T) {
	for name, statement := range map[string]string{
		"同名错误索引": "CREATE INDEX idx_usage_logs_api_key_created_cost ON usage_logs(created_at)",
		"同名表":    "CREATE TABLE idx_usage_logs_api_key_created_cost(id int)",
		"同名字段":   "ALTER TABLE usage_logs ADD COLUMN cache_creation_12h_tokens text",
		"RLS":    "ALTER TABLE usage_logs ENABLE ROW LEVEL SECURITY",
		"错误顺序账本": "INSERT INTO schema_migrations(filename,checksum) VALUES('250_openai_cache_write_ttl.sql','532551ce7aee86b2ee0a78d397d422424ceed4051e31d5f542277c80c21b8b98')",
	} {
		t.Run(name, func(t *testing.T) {
			db, _ := migration250Fixture(t)
			_, err := db.Exec(statement)
			require.NoError(t, err)
			require.Error(t, runMigration250(t, db))
		})
	}
	for name, statement := range map[string]string{
		"索引丢失":   "DROP INDEX idx_usage_logs_api_key_created_cost",
		"字段默认值":  "ALTER TABLE usage_logs ALTER COLUMN cache_creation_12h_tokens SET DEFAULT 1",
		"部分解除保护": "ALTER TABLE channel_model_pricing DROP CONSTRAINT sub2api_bg250_price",
		"保护定义":   "ALTER TABLE channel_model_pricing DROP CONSTRAINT sub2api_bg250_price; ALTER TABLE channel_model_pricing ADD CONSTRAINT sub2api_bg250_price CHECK(cache_write_12h_price IS NULL OR cache_write_12h_price=0)",
	} {
		t.Run(name, func(t *testing.T) {
			db, _ := migration250Fixture(t)
			require.NoError(t, runMigration250(t, db))
			_, err := db.Exec(statement)
			require.NoError(t, err)
			require.Error(t, runMigration250(t, db))
		})
	}
}
